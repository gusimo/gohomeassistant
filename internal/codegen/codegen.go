// Package codegen generates the typed "ent" package from Home Assistant's
// states and service descriptions.
//
// Generated API:
//
//	ent.Light.Kitchen                       // LightEntity (embeds ha.Entity)
//	ent.Light.Kitchen.TurnOn(ent.LightTurnOn{BrightnessPct: 50})
//	ent.Svc.Notify.MobileAppPhone(ent.NotifyMobileAppPhone{Message: "hi"})
//	ent.Svc.Light.TurnOn(ha.Target{AreaID: []string{"kitchen"}})
package codegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"sort"
	"strings"
	"unicode"
)

// ModulePath is the import path of the generated module. It only exists
// locally (resolved through the go.work GoHomeAssistant writes for each
// project), hence the .local domain: it can't be fetched from anywhere.
const ModulePath = "gohomeassistant.local/ent"

// State is the part of an HA state the generator uses.
type State struct {
	EntityID   string         `json:"entity_id"`
	Attributes map[string]any `json:"attributes"`
}

// Service is an entry of the get_services result.
type Service struct {
	Name        string           `json:"name"`
	Description string           `json:"description"`
	Fields      map[string]Field `json:"fields"`
	Target      *struct {
		Entity json.RawMessage `json:"entity"`
	} `json:"target"`
}

// Field is a service field, or a section grouping more fields.
type Field struct {
	Name        string                     `json:"name"`
	Description string                     `json:"description"`
	Required    bool                       `json:"required"`
	Example     any                        `json:"example"`
	Selector    map[string]json.RawMessage `json:"selector"`
	Fields      map[string]Field           `json:"fields"` // section
}

// Services is the get_services result: domain -> service -> description.
type Services map[string]map[string]Service

// Generate returns the gofmt'ed source of package ent and, per entity ID,
// the Go expression referring to it (e.g. "ent.Light.Kitchen").
func Generate(states []State, services Services) ([]byte, map[string]string, error) {
	g := &gen{top: names{}, refs: map[string]string{}}
	g.top.reserve("Svc", "first")
	g.emit(states, services)
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("format generated code: %w\n%s", err, g.buf.String())
	}
	return src, g.refs, nil
}

// Stub is the package written before the first successful generation.
// It defines an empty Svc, so code like the project template's "_ = ent.Svc"
// builds before Home Assistant was reachable.
func Stub() []byte {
	return []byte("// Code generated by GoHomeAssistant. DO NOT EDIT.\n\n// Package ent has not been generated yet: GoHomeAssistant could not reach Home Assistant.\npackage ent\n\n// Svc will contain all services.\nvar Svc = struct{}{}\n")
}

type gen struct {
	buf  bytes.Buffer
	top  names
	refs map[string]string
}

func (g *gen) p(format string, args ...any) { fmt.Fprintf(&g.buf, format, args...) }

type svcInfo struct {
	domain, service string
	params          string // params type name
	targetDomains   []string
	hasTarget       bool
}

func (g *gen) emit(states []State, services Services) {
	g.p("// Code generated by GoHomeAssistant from your Home Assistant instance. DO NOT EDIT.\n\n")
	g.p("// Package ent contains typed references to all entities and services of\n// your Home Assistant instance. It is regenerated when entities or services change.\n")
	g.p("package ent\n\nimport ha %q\n\n", "gohomeassistant.local/sdk")
	g.p("func first[T any](p []T) (v T) {\n\tif len(p) > 0 {\n\t\tv = p[0]\n\t}\n\treturn\n}\n\n")

	// Entities grouped by domain.
	byDomain := map[string][]State{}
	for _, s := range states {
		d, _, ok := strings.Cut(s.EntityID, ".")
		if ok {
			byDomain[d] = append(byDomain[d], s)
		}
	}
	domains := sortedKeys(byDomain)
	entityType := map[string]string{}
	domainVar := map[string]string{}
	for _, d := range domains {
		domainVar[d] = g.top.add(goName(d))
		entityType[d] = g.top.add(goName(d) + "Entity")
	}

	// Services: params types first, so names are known.
	var svcs []svcInfo
	for _, d := range sortedKeys(services) {
		for _, s := range sortedKeys(services[d]) {
			sv := services[d][s]
			info := svcInfo{domain: d, service: s, params: g.top.add(goName(d) + goName(s))}
			if sv.Target != nil {
				info.hasTarget = true
				info.targetDomains = targetDomains(sv.Target.Entity)
			}
			svcs = append(svcs, info)
			g.params(info.params, d, s, sv)
		}
	}

	// Entity types with their service methods.
	for _, d := range domains {
		t := entityType[d]
		g.p("// %s is an entity of domain %s.\ntype %s struct{ ha.Entity }\n\n", t, d, t)
		methods := names{}
		for _, si := range svcs {
			if !si.hasTarget || !slices.Contains(si.targetDomains, d) {
				continue
			}
			name := goName(si.service)
			if si.domain != d { // e.g. sonos.join on media_player
				name = goName(si.domain) + name
			}
			if entityMethods[name] { // e.g. light.state vs ha.Entity.State
				name += "Service"
			}
			m := methods.add(name)
			g.p("// %s calls %s.%s for this entity. See %s for the parameters.\n", m, si.domain, si.service, si.params)
			g.p("func (e %s) %s(p ...%s) error {\n\treturn e.CallService(%q, %q, first(p).data())\n}\n\n", t, m, si.params, si.domain, si.service)
		}
	}

	// Domain variables with one field per entity.
	for _, d := range domains {
		ents := byDomain[d]
		sort.Slice(ents, func(i, j int) bool { return ents[i].EntityID < ents[j].EntityID })
		fields := names{}
		g.p("// %s contains all %s entities.\nvar %s = struct {\n", domainVar[d], d, domainVar[d])
		var inits []string
		for _, e := range ents {
			_, obj, _ := strings.Cut(e.EntityID, ".")
			f := fields.add(goName(obj))
			g.refs[e.EntityID] = "ent." + domainVar[d] + "." + f
			g.p("\t// %s is %s.\n\t%s %s\n", f, describeEntity(e), f, entityType[d])
			inits = append(inits, fmt.Sprintf("\t%s: %s{ha.Entity{ID: %q}},\n", f, entityType[d], e.EntityID))
		}
		g.p("}{\n%s}\n\n", strings.Join(inits, ""))
	}

	// Svc: every service, grouped by domain.
	g.p("// Svc contains all services, grouped by domain.\nvar Svc = struct {\n")
	svcDomains := names{}
	domainField := map[string]string{}
	for _, d := range sortedKeys(services) {
		f := svcDomains.add(goName(d))
		domainField[d] = f
		g.p("\t%s svc%s\n", f, f)
	}
	g.p("}{}\n\n")
	methodNames := map[string]names{}
	for _, d := range sortedKeys(services) {
		g.p("type svc%s struct{}\n\n", domainField[d])
		methodNames[d] = names{}
	}
	for _, si := range svcs {
		recv := "svc" + domainField[si.domain]
		m := methodNames[si.domain].add(goName(si.service))
		g.p("// %s calls %s.%s. See %s for the parameters.\n", m, si.domain, si.service, si.params)
		if si.hasTarget {
			g.p("func (%s) %s(target ha.Target, p ...%s) error {\n\treturn ha.CallService(%q, %q, target, first(p).data())\n}\n\n", recv, m, si.params, si.domain, si.service)
		} else {
			g.p("func (%s) %s(p ...%s) error {\n\treturn ha.CallService(%q, %q, ha.Target{}, first(p).data())\n}\n\n", recv, m, si.params, si.domain, si.service)
		}
	}
}

type field struct {
	key, name, typ, zeroCheck string
	doc                       string
}

func (g *gen) params(typeName, domain, service string, sv Service) {
	flat := map[string]Field{}
	flatten(sv.Fields, flat)
	fields := names{}
	fields.reserve("Extra")
	var fs []field
	for _, key := range sortedKeys(flat) {
		f := flat[key]
		typ, zero := goType(f.Selector)
		fs = append(fs, field{key: key, name: fields.add(goName(key)), typ: typ, zeroCheck: zero, doc: describeField(key, f)})
	}

	doc := fmt.Sprintf("%s are the parameters of %s.%s.", typeName, domain, service)
	if t := oneLine(sv.Name); t != "" {
		doc += " " + t + "."
	}
	if t := oneLine(sv.Description); t != "" {
		doc += "\n// " + t
	}
	g.p("// %s\n// Zero values are not sent.\ntype %s struct {\n", doc, typeName)
	for _, f := range fs {
		g.p("\t// %s\n\t%s %s\n", f.doc, f.name, f.typ)
	}
	g.p("\t// Extra holds additional fields, sent as-is.\n\tExtra map[string]any\n}\n\n")

	g.p("func (p %s) data() map[string]any {\n\tm := map[string]any{}\n", typeName)
	for _, f := range fs {
		g.p("\tif %s {\n\t\tm[%q] = p.%s\n\t}\n", fmt.Sprintf(f.zeroCheck, "p."+f.name), f.key, f.name)
	}
	g.p("\tfor k, v := range p.Extra {\n\t\tm[k] = v\n\t}\n\treturn m\n}\n\n")
}

func flatten(in, out map[string]Field) {
	for k, f := range in {
		if f.Fields != nil && f.Selector == nil {
			flatten(f.Fields, out)
			continue
		}
		out[k] = f
	}
}

// goType maps an HA selector to a Go type and a zero check (%s = value).
func goType(sel map[string]json.RawMessage) (typ, zeroCheck string) {
	for kind, raw := range sel {
		var opts struct {
			Multiple bool `json:"multiple"`
		}
		_ = json.Unmarshal(raw, &opts)
		switch kind {
		case "number", "color_temp":
			return "float64", "%s != 0"
		case "boolean":
			return "bool", "%s"
		case "color_rgb":
			return "[]int", "len(%s) > 0"
		case "text", "select", "state", "entity", "device", "area", "datetime", "date", "time",
			"icon", "template", "theme", "conversation_agent", "backup_location", "config_entry",
			"addon", "app", "statistic", "label", "floor", "language", "assist_pipeline":
			if opts.Multiple {
				return "[]string", "len(%s) > 0"
			}
			return "string", `%s != ""`
		}
	}
	return "any", "%s != nil"
}

func describeField(key string, f Field) string {
	var parts []string
	if t := oneLine(f.Name); t != "" && !strings.EqualFold(t, key) {
		parts = append(parts, t+".")
	}
	if t := oneLine(f.Description); t != "" {
		parts = append(parts, t)
	}
	for kind, raw := range f.Selector {
		var o struct {
			Min     *float64 `json:"min"`
			Max     *float64 `json:"max"`
			Unit    string   `json:"unit_of_measurement"`
			Options []any    `json:"options"`
		}
		_ = json.Unmarshal(raw, &o)
		s := "Selector: " + kind
		if o.Min != nil && o.Max != nil {
			s += fmt.Sprintf(" %g–%g", *o.Min, *o.Max)
		}
		if o.Unit != "" {
			s += " " + o.Unit
		}
		if len(o.Options) > 0 {
			s += ", one of: " + options(o.Options, 12)
		}
		parts = append(parts, s+".")
	}
	if f.Example != nil {
		parts = append(parts, fmt.Sprintf("Example: %v.", oneLine(fmt.Sprint(f.Example))))
	}
	if f.Required {
		parts = append(parts, "Required.")
	}
	return fmt.Sprintf("%s (%q). %s", goName(key), key, strings.Join(parts, " "))
}

func options(opts []any, max int) string {
	var out []string
	for i, o := range opts {
		if i == max {
			out = append(out, fmt.Sprintf("… (%d more)", len(opts)-max))
			break
		}
		if m, ok := o.(map[string]any); ok { // {"value": ..., "label": ...}
			o = m["value"]
		}
		out = append(out, fmt.Sprintf("%q", fmt.Sprint(o)))
	}
	return strings.Join(out, ", ")
}

func describeEntity(e State) string {
	s := e.EntityID
	if n, ok := e.Attributes["friendly_name"].(string); ok && n != "" {
		s += fmt.Sprintf(" (%q)", oneLine(n))
	}
	if u, ok := e.Attributes["unit_of_measurement"].(string); ok && u != "" {
		s += ", unit " + oneLine(u)
	}
	return s
}

// targetDomains extracts the entity domains of a service target. HA sends
// either one filter object or a list of them; domain is a string or a list.
func targetDomains(raw json.RawMessage) []string {
	var filters []struct {
		Domain json.RawMessage `json:"domain"`
	}
	if json.Unmarshal(raw, &filters) != nil {
		var one struct {
			Domain json.RawMessage `json:"domain"`
		}
		if json.Unmarshal(raw, &one) != nil {
			return nil
		}
		filters = append(filters, one)
	}
	var out []string
	for _, f := range filters {
		var list []string
		if json.Unmarshal(f.Domain, &list) != nil {
			var s string
			if json.Unmarshal(f.Domain, &s) == nil && s != "" {
				list = []string{s}
			}
		}
		out = append(out, list...)
	}
	return out
}

// goName turns snake_case identifiers into exported Go names.
func goName(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		if !unicode.IsLetter(r) && !unicode.IsDigit(r) || r > unicode.MaxASCII {
			upper = true
			continue
		}
		if upper {
			r = unicode.ToUpper(r)
			upper = false
		}
		b.WriteRune(r)
	}
	n := b.String()
	if n == "" || !unicode.IsLetter(rune(n[0])) {
		n = "X" + n
	}
	return n
}

// entityMethods are the names ha.Entity already uses.
var entityMethods = names{"ID": true, "Entity": true, "State": true, "Value": true, "IsOn": true,
	"Float": true, "Attr": true, "OnChange": true, "CallService": true}

// names hands out unique identifiers within one scope.
type names map[string]bool

func (n names) reserve(ids ...string) {
	for _, id := range ids {
		n[id] = true
	}
}

func (n names) add(id string) string {
	out := id
	for i := 2; n[out]; i++ {
		out = fmt.Sprintf("%s_%d", id, i)
	}
	n[out] = true
	return out
}

// oneLine makes text safe for a single-line comment.
func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	return strings.TrimSuffix(s, ".")
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
